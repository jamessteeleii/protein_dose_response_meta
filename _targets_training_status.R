# Separate opt-in process/store. Adapters are local to this targets script.
library(targets)
workers <- suppressWarnings(as.integer(Sys.getenv("PROTEIN_MODEL_WORKERS", "4")))
if (length(workers) != 1L || is.na(workers) || workers < 1L) stop("Invalid PROTEIN_MODEL_WORKERS.")
future::plan(future::multisession, workers = workers)
tar_option_set(packages = c("here", "qs", "tidyverse", "metafor", "mgcv", "splines", "lspline",
  "brms", "rstan", "posterior", "loo", "matrixStats", "digest"), seed = 651988L,
  format = "qs", memory = "transient", garbage_collection = TRUE, storage = "worker", retrieval = "worker")
for (path in c("R/functions.R", "R/primary_model_diagnostics.R", "R/primary_model_loo.R",
  "R/primary_model_averaging.R", "R/incremental_update.R", "R/update_2026_absolute_exposures.R",
  "R/verification_artifacts.R", "R/age_duration_interactions.R", "R/training_status_workflow.R",
  "R/training_status_exact_remedies.R", "R/training_status_marginal_exact.R")) tar_source(path)
tst_cue <- function(phase) tar_cue(mode = if (iad_phase(phase)) "thorough" else "never")
list(
  tar_target(tst_sources, iad_checkpoint_inputs(), format = "file"),
  tar_target(tst_checkpoints, iad_read_checkpoints(tst_sources)),
  tar_target(tst_prior_file, here::here("sensitivity", "age-duration-base-priors.csv"), format = "file"),
  tar_target(tst_priors, iad_priors(tst_prior_file)),
  tar_target(tst_specification, iad_specifications(tst_checkpoints), iteration = "list"),
  tar_target(tst_preflight, iad_preflight(tst_specification, tst_checkpoints, tst_priors)),
  tar_target(tst_preparation_files, tst_prepare(tst_checkpoints, tst_specification, tst_preflight), format = "file"),
  tar_target(tst_pilot_specification, iad_pilot_specs(tst_specification), iteration = "list"),
  tar_target(tst_remaining_specification, Filter(function(s) !s$model_index %in% c(6L, 26L), tst_specification), iteration = "list"),
  tar_target(tst_pilot_file, iad_fit(tst_pilot_specification, tst_checkpoints, tst_priors, tst_preflight, "pilot"),
    pattern = map(tst_pilot_specification), cue = tst_cue("pilot"), format = "file", iteration = "list", error = "continue"),
  tar_target(tst_pilot_diagnostic, iad_diagnose(tst_pilot_file), pattern = map(tst_pilot_file), iteration = "list"),
  tar_target(tst_pilot_summary, iad_diagnostic_summary(tst_pilot_diagnostic)),
  tar_target(tst_pilot_audit_files, iad_diagnostic_files(tst_pilot_diagnostic, "pilot"), format = "file"),
  tar_target(tst_fit_file, iad_fit(tst_remaining_specification, tst_checkpoints, tst_priors, tst_preflight, "fit", tst_pilot_summary),
    pattern = map(tst_remaining_specification), cue = tst_cue("fit"), format = "file", iteration = "list", error = "continue"),
  tar_target(tst_fit_diagnostic, iad_diagnose(tst_fit_file), pattern = map(tst_fit_file), iteration = "list"),
  tar_target(tst_initial_summary, iad_diagnostic_summary(c(tst_pilot_diagnostic, tst_fit_diagnostic))),
  tar_target(tst_initial_audit_files, iad_diagnostic_files(c(tst_pilot_diagnostic, tst_fit_diagnostic), "initial"), format = "file"),
  tar_target(tst_remedy_file, here::here("sensitivity", "training-status-remedies.csv"), format = "file"),
  tar_target(tst_remedy_specification, iad_remedy_specs(tst_specification, tst_remedy_file, tst_initial_summary), iteration = "list"),
  tar_target(tst_remedy_fit_file, iad_fit_remedy(tst_remedy_specification, tst_checkpoints, tst_priors, tst_preflight),
    pattern = map(tst_remedy_specification), cue = tst_cue("remedy"), format = "file", iteration = "list", error = "continue"),
  tar_target(tst_remedy_diagnostic, iad_diagnose_remedy(tst_remedy_fit_file), pattern = map(tst_remedy_fit_file), iteration = "list"),
  tar_target(tst_accepted_record, iad_accepted(tst_initial_summary, iad_diagnostic_summary(tst_remedy_diagnostic),
    tst_specification, tst_checkpoints), iteration = "list"),
  tar_target(tst_accepted_audit_file, iad_csv(dplyr::bind_rows(tst_accepted_record), iad_path("diagnostics", "accepted.csv")), format = "file"),
  tar_target(tst_loo_file, iad_compute_loo(tst_accepted_record), pattern = map(tst_accepted_record), cue = tst_cue("loo"),
    format = "file", iteration = "list", error = "continue"),
  tar_target(tst_loo_audit, iad_loo_audit(tst_loo_file)),
  tar_target(tst_loo_audit_files, iad_write_loo_audit(tst_loo_audit), format = "file"),
  tar_target(tst_exact_record, tst_loo_audit$cases, iteration = "list"),
  tar_target(tst_exact_file, iad_exact(tst_exact_record, compact = TRUE), pattern = map(tst_exact_record), cue = tst_cue("exact"),
    format = "file", iteration = "list", error = "continue"),
  tar_target(tst_exact_diagnostic, iad_exact_diagnostics(tst_exact_file), pattern = map(tst_exact_file), iteration = "list"),
  tar_target(tst_exact_audit_file, iad_csv(dplyr::bind_rows(tst_exact_diagnostic), iad_path("loo", "exact_diagnostics.csv")), format = "file"),
  tar_target(tst_exact_remedy_ledger_file, here::here("sensitivity", "training-status-exact-remedies.csv"), format = "file"),
  tar_target(tst_exact_review_plan, tst_exact_remedy_plan(tst_exact_file, tst_exact_remedy_ledger_file), iteration = "list"),
  tar_target(tst_exact_review_file, tst_review_exact(tst_exact_review_plan), pattern = map(tst_exact_review_plan),
    cue = tst_cue("exact_remedy"), format = "file", iteration = "list", error = "continue"),
  tar_target(tst_exact_review_diagnostic, iad_exact_diagnostics(tst_exact_review_file),
    pattern = map(tst_exact_review_file), iteration = "list"),
  tar_target(tst_exact_review_audit_file, iad_csv(dplyr::bind_rows(tst_exact_review_diagnostic),
    iad_path("loo", "exact_review_diagnostics.csv")), format = "file"),
  tar_target(tst_marginal_pilot_file, iad_path("loo", "marginal_pilot", "model_26_observation_0080.qs"), format = "file"),
  tar_target(tst_marginal_plan, Filter(function(x) !is.null(x$remedy), tst_exact_review_plan), iteration = "list"),
  tar_target(tst_marginal_file, tst_marginal_exact_checkpoint(tst_marginal_plan, tst_marginal_pilot_file),
    pattern = map(tst_marginal_plan), cue = tst_cue("exact_marginal"), format = "file", iteration = "list", error = "continue"),
  tar_target(tst_marginal_review_paths, as.list(tst_select_marginal_exact_paths(tst_exact_file, tst_marginal_file)), iteration = "list"),
  tar_target(tst_marginal_audit_file, iad_csv(purrr::map_dfr(tst_marginal_review_paths, iad_exact_diagnostics),
    iad_path("loo", "marginal_review_diagnostics.csv")), format = "file"),
  tar_target(tst_correction_file, iad_score_exact(tst_marginal_review_paths), pattern = map(tst_marginal_review_paths), cue = tst_cue("correction"),
    format = "file", iteration = "list", error = "continue"),
  tar_target(tst_final_loo_files, iad_finalise_loo(tst_loo_audit, tst_correction_file), format = "file"),
  tar_target(tst_combined_record, iad_combine(tst_checkpoints, tst_accepted_record, tst_final_loo_files),
    cue = tst_cue("combine"), iteration = "list"),
  tar_target(tst_combination_files, iad_write_combination(tst_combined_record), format = "file"),
  tar_target(tst_report_files, tst_report(tst_combined_record, tst_checkpoints), pattern = map(tst_combined_record),
    cue = tst_cue("report"), format = "file", iteration = "list", error = "continue"),
  tar_target(tst_supplement_file, tst_supplement(tst_report_files, tst_combined_record), cue = tst_cue("report"), format = "file")
)
